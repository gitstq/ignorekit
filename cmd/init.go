package cmd

import (
	"flag"
	"os"
	"path/filepath"
	"strings"

	"github.com/gitstq/ignorekit/internal/engine"
	"github.com/gitstq/ignorekit/internal/term"
)

func init() {
	register(command{name: "init", short: "generate a .gitignore", run: runInit})
}

// renderGenerated builds a complete standalone .gitignore from desired rules.
func renderGenerated(res *engine.Result) string {
	var b strings.Builder
	b.WriteString("# .gitignore generated by ignorekit (offline, zero-dependency)\n")
	b.WriteString("# https://github.com/gitstq/ignorekit\n\n")
	last := ""
	for _, r := range res.Desired {
		if r.Section != last {
			if b.Len() > 0 {
				b.WriteString("\n")
			}
			b.WriteString("# --- " + r.Section + " ---\n")
			last = r.Section
		}
		b.WriteString(r.Line + "\n")
	}
	return b.String()
}

func runInit(args []string) int {
	fs := flag.NewFlagSet("init", flag.ContinueOnError)
	o := &commonOpts{}
	bindCommon(fs, o)
	force := fs.Bool("force", false, "overwrite an existing .gitignore")
	if err := parse(fs, args); err != nil {
		return exitError
	}
	applyColor(o)

	res, err := engine.Analyze(o.dir)
	if err != nil {
		errf("error: %v\n", err)
		return exitError
	}
	content := renderGenerated(res)

	if !o.write {
		outf("%s", content)
		if len(res.Desired) == 0 {
			errf("%s\n", term.Yellow("no tools detected; .gitignore is empty"))
		}
		return exitOK
	}

	gi := filepath.Join(res.Root, ".gitignore")
	if res.GitignorePresent && !*force {
		errf("%s .gitignore already exists.\nUse %s to merge safely, or %s to overwrite.\n",
			term.Yellow("!"), term.Cyan("ignorekit apply"), term.Cyan("ignorekit init --write --force"))
		return exitError
	}
	if err := os.WriteFile(gi, []byte(content), 0o644); err != nil {
		errf("error writing .gitignore: %v\n", err)
		return exitError
	}
	outf("%s wrote %s (%d rules)\n", term.Green("✔"), gi, len(res.Desired))
	return exitOK
}
